/**
 * reportService.ts
 * Generates a PowerPoint (.pptx) Buyer Selection report.
 *
 * Layout (LAYOUT_WIDE = 13.33 × 7.5 inches):
 * ┌─────────────────────────────────────────────────────────────────────────────┐
 * │ Project Name : XXX        Buyer Selection App        Buyer Selection Date:  │
 * ├──────────────┬───────────────────────────┬──────────────────────────────────┤
 * │              │  Front                    │  Fabric                          │
 * │  AI Generated│                           │                                  │
 * │  Image       ├───────────────────────────┼──────────────────────────────────┤
 * │              │  Back                     │  Info block (right-aligned labels│
 * │              │                           │  including INTERNAL NOTES)       │
 * ├──────────────┴───────────────────────────┴──────────────────────────────────┤
 * │ Page X of Y          Generated By : Name                Print Date : Date   │
 * └─────────────────────────────────────────────────────────────────────────────┘
 */

import PptxGenJS from 'pptxgenjs';
import type { ProjectItem } from './projectService';
import type { TableType } from '../types/table';
import type { InforUser, ColorwayOption } from '../types/api';
import type { GroupedStyle } from '../types/projects';
import { resolveImageBlob, isPlmDefaultImage } from '../utils/image';
import { fetchStyleImage } from './api';

// ─── Slide layout constants (LAYOUT_WIDE = 13.33 × 7.5 inches) ───────────────
const SLIDE_W = 13.33;
const SLIDE_H = 7.5;

// Header band
const HDR_Y = 0.20;
const HDR_H = 0.50;

// Content grid
const GRID_X = 0.20;
const GRID_Y = 0.85;
const GAP = 0.12;

const FOOT_Y = SLIDE_H - 0.65;
const FOOT_H = 0.45;

const GRID_H = FOOT_Y - GRID_Y - 0.12; // ≈ 5.88"

// Left column (AI Generated Image)
const AI_W = 3.85;

// Middle column (Front / Back stacked)
const MID_X = GRID_X + AI_W + GAP; // 4.17"
const MID_W = 4.25;
const CELL_H = (GRID_H - GAP) / 2;  // ≈ 2.88"

// Right column (Fabric / Info stacked)
const RIGHT_X = MID_X + MID_W + GAP; // 8.54"
const RIGHT_W = SLIDE_W - RIGHT_X - GRID_X; // ≈ 4.59"

// Caption bar height at bottom of image cells
const CAP_H = 0.28;

// Colours
const RED = 'A93226'; // Deep elegant dark red as in reference screenshot
const DARK = '1A1A2E';
const GREY = '777777';
const BORDER = { type: 'solid' as const, pt: 1, color: 'CCCCCC' };
const BG_CELL = 'F9F9F9';

// ─── Utility helpers ──────────────────────────────────────────────────────────

function blobToDataUrl(blob: Blob): Promise<string> {
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
}

/** Fetches image data through the existing backend EC2 proxy / S3 service and returns base64 data-URL */
async function fetchImgDataUrl(ref: string | null | undefined): Promise<string | null> {
  if (!ref || !ref.trim()) return null;
  try {
    if (ref.startsWith('data:')) return ref;
    const blob = await resolveImageBlob(ref);
    return blob ? await blobToDataUrl(blob) : null;
  } catch {
    return null;
  }
}

/** Parses annotatedImage JSON string into an ordered array of image URLs from current application storage */
function parseImages(annotatedImage: string | null | undefined): string[] {
  if (!annotatedImage) return [];
  const raw = String(annotatedImage).trim();
  if (!raw || raw === '[]' || raw === 'null' || raw === 'undefined') return [];

  if (raw.startsWith('[')) {
    try {
      const parsed: unknown[] = JSON.parse(raw);
      if (Array.isArray(parsed)) {
        return parsed
          .map((x) => {
            if (x && typeof x === 'object') {
              const o = x as Record<string, unknown>;
              return String(o.annotated ?? o.original ?? '').trim();
            }
            return String(x ?? '').trim();
          })
          .filter((u) => u && u !== 'null' && u !== 'undefined' && u !== '[]');
      }
    } catch {
      return [raw];
    }
  }
  return raw ? [raw] : [];
}

/** Resolves colorway name from current application database records or mapped options */
function resolveColorwayName(item: ProjectItem, plmOptions?: ColorwayOption[]): string {
  const raw = String(item.colorway || '').trim();
  if (raw && raw !== 'null' && raw !== 'undefined' && raw !== '[]' && raw !== '""') {
    return raw;
  }
  if (item.colorId && item.colorId > 0 && plmOptions && plmOptions.length > 0) {
    const match = plmOptions.find((opt) => opt.colorwayId === item.colorId);
    if (match && match.value) {
      return match.value.trim();
    }
  }
  return '—';
}

function fmtDate(d: Date | string | null | undefined): string {
  if (!d) return '';
  const dt = d instanceof Date ? d : new Date(d as string);
  if (isNaN(dt.getTime())) return String(d);
  const dd = String(dt.getDate()).padStart(2, '0');
  const mm = String(dt.getMonth() + 1).padStart(2, '0');
  return `${dd}/${mm}/${dt.getFullYear()}`;
}

// ─── Single-slide builder ─────────────────────────────────────────────────────

interface SlideImages {
  styleImg: string | null;
  front: string | null;
  back: string | null;
  fabric: string | null;
}

function addImageCell(
  slide: PptxGenJS.Slide,
  pptx: PptxGenJS,
  dataUrl: string | null,
  x: number, y: number, w: number, h: number,
  caption: string,
) {
  // Background + border rectangle
  slide.addShape(pptx.ShapeType.rect, {
    x, y, w, h,
    fill: { color: BG_CELL },
    line: BORDER,
  });

  // Image (if available from current application storage)
  if (dataUrl) {
    const imgH = h - CAP_H - 0.10;
    slide.addImage({
      data: dataUrl,
      x: x + 0.05, y: y + 0.05,
      w: w - 0.10, h: imgH,
      sizing: { type: 'contain', w: w - 0.10, h: imgH },
    });
  }

  // Caption label at bottom with visible left spacing / indent before label start
  slide.addText(caption, {
    x: x + 0.12,
    y: y + h - CAP_H,
    w: w - 0.24,
    h: CAP_H,
    fontSize: 9,
    color: '555555',
    align: 'left',
    valign: 'middle',
    margin: [0, 0, 0, 8],
  });
}

function buildSlide(
  pptx: PptxGenJS,
  item: ProjectItem,
  imgs: SlideImages,
  colorwayName: string,
  pageNum: number,
  total: number,
  projectName: string,
  selectionDate: string,
  printDate: string,
  generatedBy: string,
) {
  const slide = pptx.addSlide();

  // ── HEADER ────────────────────────────────────────────────────────────────
  // Left: Project Name
  slide.addText(`Project Name : ${projectName}`, {
    x: GRID_X, y: HDR_Y, w: 4.2, h: HDR_H,
    fontSize: 13, bold: true, color: RED,
    valign: 'middle', align: 'left',
  });

  // Center: Buyer Selection App
  slide.addText('Buyer Selection App', {
    x: (SLIDE_W - 4.5) / 2, y: HDR_Y, w: 4.5, h: HDR_H,
    fontSize: 14, bold: true, color: RED,
    valign: 'middle', align: 'center',
  });

  // Right: Buyer Selection Date
  slide.addText(`Buyer Selection Date : ${selectionDate}`, {
    x: SLIDE_W - 4.5 - GRID_X, y: HDR_Y, w: 4.5, h: HDR_H,
    fontSize: 13, bold: true, color: RED,
    valign: 'middle', align: 'right',
  });

  // ── 1. STYLE IMAGE (tall left column - AI Generated / PLM image) ────────────
  addImageCell(slide, pptx, imgs.styleImg,
    GRID_X, GRID_Y, AI_W, GRID_H,
    'AI Generated');

  // ── 2. FRONT IMAGE (mid-top) ──────────────────────────────────────────────
  addImageCell(slide, pptx, imgs.front,
    MID_X, GRID_Y, MID_W, CELL_H,
    'Front');

  // ── 3. BACK IMAGE (mid-bottom) ────────────────────────────────────────────
  const backY = GRID_Y + CELL_H + GAP;
  addImageCell(slide, pptx, imgs.back,
    MID_X, backY, MID_W, CELL_H,
    'Back');

  // ── 4. FABRIC IMAGE (right-top) ───────────────────────────────────────────
  addImageCell(slide, pptx, imgs.fabric,
    RIGHT_X, GRID_Y, RIGHT_W, CELL_H,
    'Fabric');

  // ── 5. INFORMATION BLOCK (right-bottom) ───────────────────────────────────
  const infoY = backY;
  slide.addShape(pptx.ShapeType.rect, {
    x: RIGHT_X, y: infoY, w: RIGHT_W, h: CELL_H,
    fill: { color: 'FFFFFF' },
    line: BORDER,
  });

  // Right-aligned label+value pairs (including INTERNAL NOTES)
  const styleCode = item.styleMaterialNumber || '';
  const styleDesc = item.styleMaterialName || '';
  const cwStatus = (item.colorwayStatus && item.colorwayStatus !== 'null') ? item.colorwayStatus : '—';
  const condition = item.selectionCondition || '—';
  const sampleDue = item.sampleDue ? fmtDate(item.sampleDue) : '—';
  const buyerCmt = item.buyerComments || '—';
  const internalNotes = item.internalComments || '—';

  const rows: Array<[string, string]> = [
    ['STYLE NAME', styleCode],
    ['STYLE DESCRIPTION', styleDesc],
    ['COLORWAY', colorwayName],
    ['STATUS', cwStatus],
    ['CONDITION', condition],
    ['SAMPLE DUE', sampleDue],
    ['BUYER COMMENTS', buyerCmt],
    ['INTERNAL NOTES', internalNotes],
  ];

  const textBody: PptxGenJS.TextProps[] = [];
  rows.forEach(([label, value], idx) => {
    if (idx > 0) textBody.push({ text: '\n', options: { fontSize: 3 } });
    textBody.push({ text: label + '\n', options: { bold: true, fontSize: 7.5, color: DARK } });
    textBody.push({ text: value + '\n', options: { bold: false, fontSize: 7.5, color: '444444' } });
  });

  slide.addText(textBody, {
    x: RIGHT_X + 0.10,
    y: infoY + 0.08,
    w: RIGHT_W - 0.20,
    h: CELL_H - 0.16,
    valign: 'top',
    align: 'right',
    wrap: true,
  });

  // ── FOOTER ────────────────────────────────────────────────────────────────
  slide.addText(`Page ${pageNum} of ${total}`, {
    x: GRID_X, y: FOOT_Y, w: 3.5, h: FOOT_H,
    fontSize: 9.5, color: DARK, valign: 'middle', align: 'left',
  });
  if (generatedBy) {
    slide.addText(`Generated By : ${generatedBy}`, {
      x: (SLIDE_W - 5) / 2, y: FOOT_Y, w: 5, h: FOOT_H,
      fontSize: 9, color: GREY, valign: 'middle', align: 'center',
    });
  }
  slide.addText(`Print Date : ${printDate}`, {
    x: SLIDE_W - 4.5 - GRID_X, y: FOOT_Y, w: 4.5, h: FOOT_H,
    fontSize: 9.5, color: DARK, valign: 'middle', align: 'right',
  });
}

// ─── Exported entry point ─────────────────────────────────────────────────────

export interface GenerateReportParams {
  project: TableType;
  sortedGroupedStyles?: GroupedStyle[];
  items?: ProjectItem[];
  plmColorwaysMap?: Record<string, ColorwayOption[]>;
  plmImagesMap?: Record<string, string>;
  currentUser: InforUser | null;
  logoDataUrl?: string | null;
}

/**
 * Generates and downloads a .pptx Buyer Selection report.
 *
 * Rules:
 *  • One slide per Style + Color combination.
 *  • Header: Project Name (left) | Buyer Selection App (center) | Buyer Selection Date (right).
 *  • Images: Current Application Only (AWS EC2 / S3 storage via existing backend proxy).
 *  • Info block: Style Code, Description, Colorway, Status, Condition, Due Date, Buyer Comments, Internal Notes.
 *  • Indented image labels with clear space before text start.
 */
export async function generateProjectReport(
  projectOrParams: TableType | GenerateReportParams,
  itemsArg?: ProjectItem[],
  currentUserArg?: InforUser | null,
): Promise<void> {
  const isParamsObj = 'project' in projectOrParams;
  const project: TableType = isParamsObj
    ? (projectOrParams as GenerateReportParams).project
    : (projectOrParams as TableType);

  const currentUser: InforUser | null = isParamsObj
    ? (projectOrParams as GenerateReportParams).currentUser
    : (currentUserArg ?? null);

  const plmColorwaysMap = isParamsObj
    ? (projectOrParams as GenerateReportParams).plmColorwaysMap || {}
    : {};

  const plmImagesMap: Record<string, string> = isParamsObj
    ? (projectOrParams as GenerateReportParams).plmImagesMap || {}
    : {};

  const sortedGroupedStyles = isParamsObj
    ? (projectOrParams as GenerateReportParams).sortedGroupedStyles
    : undefined;

  const rawItems = isParamsObj
    ? (projectOrParams as GenerateReportParams).items || []
    : (itemsArg || []);

  const pptx = new PptxGenJS();
  pptx.layout = 'LAYOUT_WIDE';   // 13.33" × 7.5"

  const projectName = project.ProjectName || 'Unknown Project';
  const selectionDate = fmtDate(project.SelectionDate);
  const printDate = fmtDate(new Date());
  const generatedBy = currentUser
    ? (`${currentUser.firstName} ${currentUser.lastName}`.trim() || (currentUser as unknown as { email?: string }).email || '')
    : '';

  // ── Build slide targets in exact style group order ──────────────────────────
  interface SlideTarget {
    item: ProjectItem;
    styleNumber: string;
    styleName: string;
    colorwayName: string;
    groupAnnotatedImage?: string | null;
  }

  const slideTargets: SlideTarget[] = [];

  if (sortedGroupedStyles && sortedGroupedStyles.length > 0) {
    for (const group of sortedGroupedStyles) {
      const styleNumber = group.styleMaterialNumber;
      const styleName = group.styleMaterialName || styleNumber;
      const plmOptions = plmColorwaysMap[styleNumber];

      if (group.items && group.items.length > 0) {
        for (const item of group.items) {
          const colorwayName = resolveColorwayName(item, plmOptions);
          slideTargets.push({
            item,
            styleNumber,
            styleName,
            colorwayName,
            groupAnnotatedImage: group.annotatedImage,
          });
        }
      } else {
        const dummyItem: ProjectItem = {
          projectId: project.id || 0,
          styleMaterialNumber: styleNumber,
          styleMaterialName: styleName,
          colorway: '—',
          colorwayStatus: '—',
          selectionCondition: group.selectionCondition || 'As-Is',
          sampleDue: null,
          buyerComments: '',
          internalComments: '',
          annotatedImage: group.annotatedImage,
        };
        slideTargets.push({
          item: dummyItem,
          styleNumber,
          styleName,
          colorwayName: '—',
          groupAnnotatedImage: group.annotatedImage,
        });
      }
    }
  } else {
    // Fallback: organize rawItems by StyleMaterialNumber
    const grouped: Record<string, ProjectItem[]> = {};
    for (const it of rawItems) {
      const key = it.styleMaterialNumber || 'unknown';
      if (!grouped[key]) grouped[key] = [];
      grouped[key].push(it);
    }
    for (const [key, items] of Object.entries(grouped)) {
      const plmOptions = plmColorwaysMap[key];
      const validAnnotated = items.find((it) => it.annotatedImage)?.annotatedImage;
      for (const item of items) {
        const colorwayName = resolveColorwayName(item, plmOptions);
        slideTargets.push({
          item,
          styleNumber: key,
          styleName: item.styleMaterialName || key,
          colorwayName,
          groupAnnotatedImage: validAnnotated,
        });
      }
    }
  }

  if (slideTargets.length === 0) {
    const slide = pptx.addSlide();
    slide.addText('No items found in this project.', {
      x: 1, y: 3, w: 11, h: 1,
      fontSize: 18, color: GREY, align: 'center',
    });
    await pptx.writeFile({ fileName: `${projectName}-Report.pptx` });
    return;
  }

  const total = slideTargets.length;

  // ── Build slides sequentially ─────────────────────────────────────────
  for (let i = 0; i < slideTargets.length; i++) {
    const target = slideTargets[i];
    const { item, colorwayName, groupAnnotatedImage } = target;

    // Retrieve images from current application storage (item or group annotatedImage)
    const imgRefs = parseImages(item.annotatedImage || groupAnnotatedImage);

    // Cell 1 — AI Generated slot: MUST ALWAYS show the PLM style image
    let plmImageRef: string | null = plmImagesMap[target.styleNumber] || null;

    // If not in plmImagesMap, check if annotatedImage contains the auto-saved PLM default image
    if (!plmImageRef) {
      const defaultS3 = imgRefs.find((r) => isPlmDefaultImage(r));
      if (defaultS3) {
        plmImageRef = defaultS3;
      }
    }

    // If still not available and currentUser is present, fetch it directly from PLM
    if (!plmImageRef && currentUser && target.styleNumber) {
      try {
        plmImageRef = await fetchStyleImage(target.styleNumber, currentUser);
        if (plmImageRef) {
          plmImagesMap[target.styleNumber] = plmImageRef;
        }
      } catch (e) {
        console.warn(`[reportService] Could not fetch PLM image for ${target.styleNumber}:`, e);
      }
    }

    const styleImgRef: string | null = plmImageRef || null;

    // Cells 2-4 — User Annotations (Front, Back, Fabric)
    // Filter out the PLM default image so user annotations map correctly to Front, Back, Fabric
    const annotations = imgRefs.filter((r) => !isPlmDefaultImage(r));
    const frontRef: string | null = annotations[0] || null;
    const backRef: string | null = annotations[1] || null;
    const fabricRef: string | null = annotations[2] || null;

    // Fetch binary data URLs through the existing EC2 / S3 backend service
    const [styleImg, front, back, fabric] = await Promise.all([
      fetchImgDataUrl(styleImgRef),
      fetchImgDataUrl(frontRef),
      fetchImgDataUrl(backRef),
      fetchImgDataUrl(fabricRef),
    ]);

    buildSlide(
      pptx,
      item,
      { styleImg, front, back, fabric },
      colorwayName,
      i + 1,
      total,
      projectName,
      selectionDate,
      printDate,
      generatedBy,
    );
  }

  await pptx.writeFile({ fileName: `${projectName}-Report.pptx` });
}
